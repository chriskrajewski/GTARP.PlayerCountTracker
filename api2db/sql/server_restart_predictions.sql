-- ============================================================================
-- 1. CREATE PREDICTIONS TABLE
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.server_restart_predictions (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  server_id TEXT NOT NULL,
  next_restart_time TIMESTAMP WITH TIME ZONE,
  confidence INTEGER DEFAULT 0,
  detected_pattern TEXT,
  last_restart_time TIMESTAMP WITH TIME ZONE,
  average_downtime INTEGER DEFAULT 0,
  pattern_type TEXT, -- 'fixed-interval', 'fixed-time', 'irregular'
  pattern_interval NUMERIC, -- hours for fixed-interval
  pattern_time_of_day TEXT, -- HH:MM for fixed-time
  pattern_variance INTEGER, -- minutes
  pattern_occurrences INTEGER DEFAULT 0,
  detected_events_count INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  CONSTRAINT unique_server_predictions UNIQUE(server_id)
);

-- Create indexes for fast lookups
CREATE INDEX IF NOT EXISTS idx_server_restart_predictions_server_id 
  ON public.server_restart_predictions(server_id);

CREATE INDEX IF NOT EXISTS idx_server_restart_predictions_updated_at 
  ON public.server_restart_predictions(updated_at DESC);

-- ============================================================================
-- 2. CREATE RESTART EVENTS TABLE (for debugging/analysis)
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.server_restart_events (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  server_id TEXT NOT NULL,
  event_timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
  player_count_before INTEGER,
  player_count_after INTEGER,
  downtime_minutes INTEGER,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_server_restart_events_server_id 
  ON public.server_restart_events(server_id);

CREATE INDEX IF NOT EXISTS idx_server_restart_events_timestamp 
  ON public.server_restart_events(event_timestamp DESC);

-- ============================================================================
-- 3. HELPER FUNCTION: Detect Restart Events
-- ============================================================================

CREATE OR REPLACE FUNCTION detect_restart_events(
  p_server_id TEXT,
  p_days_back INTEGER DEFAULT 14
)
RETURNS TABLE (
  event_timestamp TIMESTAMP WITH TIME ZONE,
  player_count_before INTEGER,
  player_count_after INTEGER,
  downtime_minutes INTEGER
) AS $$
DECLARE
  v_start_date TIMESTAMP WITH TIME ZONE;
  v_prev_count INTEGER;
  v_prev_timestamp TIMESTAMP WITH TIME ZONE;
  v_curr_count INTEGER;
  v_curr_timestamp TIMESTAMP WITH TIME ZONE;
  v_drop_percentage NUMERIC;
  v_recovery_found BOOLEAN;
  v_recovery_time INTEGER;
  v_recovery_count INTEGER;
  v_time_diff_minutes NUMERIC;
  v_data RECORD;
  v_recovery_record RECORD;
BEGIN
  v_start_date := NOW() - (p_days_back || ' days')::INTERVAL;

  -- Get all player counts for this server, sorted by timestamp
  v_prev_count := NULL;
  v_prev_timestamp := NULL;

  FOR v_data IN
    SELECT player_count, timestamp
    FROM player_counts
    WHERE server_id = p_server_id
      AND timestamp >= v_start_date
    ORDER BY timestamp ASC
  LOOP
    v_curr_count := v_data.player_count;
    v_curr_timestamp := v_data.timestamp;

    -- Check for rapid drops (need previous data point)
    IF v_prev_count IS NOT NULL THEN
      -- Calculate time difference in minutes
      v_time_diff_minutes := EXTRACT(EPOCH FROM (v_curr_timestamp - v_prev_timestamp)) / 60;

      -- Only check if within 30 minute window
      IF v_time_diff_minutes <= 30 AND v_time_diff_minutes > 0 THEN
        -- Calculate drop percentage
        v_drop_percentage := CASE 
          WHEN v_prev_count > 0 THEN ((v_prev_count - v_curr_count) / v_prev_count::NUMERIC) * 100
          ELSE 0
        END;

        -- Look for drops >80% to near-zero (<5 players)
        IF v_drop_percentage > 80 AND v_curr_count < 5 THEN
          -- Check for recovery within 30 minutes after the drop
          v_recovery_found := FALSE;
          v_recovery_time := 0;

          FOR v_recovery_record IN
            SELECT player_count, timestamp
            FROM player_counts
            WHERE server_id = p_server_id
              AND timestamp > v_curr_timestamp
              AND timestamp <= v_curr_timestamp + INTERVAL '30 minutes'
            ORDER BY timestamp ASC
          LOOP
            -- Recovery is when player count reaches >10% of pre-restart level
            IF v_recovery_record.player_count > (v_prev_count * 0.1) THEN
              v_recovery_found := TRUE;
              v_recovery_time := ROUND(EXTRACT(EPOCH FROM (v_recovery_record.timestamp - v_curr_timestamp)) / 60)::INTEGER;
              EXIT;
            END IF;
          END LOOP;

          -- If recovery found, record as restart event
          IF v_recovery_found THEN
            event_timestamp := v_curr_timestamp;
            player_count_before := v_prev_count;
            player_count_after := v_curr_count;
            downtime_minutes := v_recovery_time;
            RETURN NEXT;
          END IF;
        END IF;
      END IF;
    END IF;

    -- Move to next iteration
    v_prev_count := v_curr_count;
    v_prev_timestamp := v_curr_timestamp;
  END LOOP;
END;
$$ LANGUAGE plpgsql STABLE;

-- ============================================================================
-- 4. HELPER FUNCTION: Analyze Restart Pattern
-- ============================================================================

CREATE OR REPLACE FUNCTION analyze_restart_pattern(
  p_server_id TEXT,
  p_days_back INTEGER DEFAULT 14
)
RETURNS TABLE (
  pattern_type TEXT,
  pattern_interval NUMERIC,
  pattern_time_of_day TEXT,
  pattern_variance INTEGER,
  pattern_occurrences INTEGER,
  confidence INTEGER
) AS $$
DECLARE
  v_events RECORD;
  v_event_count INTEGER := 0;
  v_event_timestamps TIMESTAMP WITH TIME ZONE[] := ARRAY[]::TIMESTAMP WITH TIME ZONE[];
  v_intervals NUMERIC[] := ARRAY[]::NUMERIC[];
  v_avg_interval NUMERIC := 0;
  v_variance NUMERIC := 0;
  v_variance_minutes INTEGER := 0;
  v_time_of_day_map JSONB := '{}'::JSONB;
  v_most_common_time TEXT := '';
  v_max_occurrences INTEGER := 0;
  v_confidence INTEGER := 0;
  v_base_confidence INTEGER := 0;
  i INTEGER;
  v_interval_hours NUMERIC;
  v_time_key TEXT;
  v_time_count INTEGER;
BEGIN
  -- Get all restart events
  FOR v_events IN
    SELECT event_timestamp FROM detect_restart_events(p_server_id, p_days_back)
    ORDER BY event_timestamp ASC
  LOOP
    v_event_count := v_event_count + 1;
    v_event_timestamps := array_append(v_event_timestamps, v_events.event_timestamp);
  END LOOP;

  -- Need at least 2 events to detect a pattern
  IF v_event_count < 2 THEN
    pattern_type := 'insufficient-data';
    pattern_occurrences := v_event_count;
    confidence := 0;
    RETURN NEXT;
    RETURN;
  END IF;

  -- Calculate intervals between consecutive events (in hours)
  FOR i IN 1..(v_event_count - 1) LOOP
    v_interval_hours := EXTRACT(EPOCH FROM (v_event_timestamps[i + 1] - v_event_timestamps[i])) / 3600;
    v_intervals := array_append(v_intervals, v_interval_hours);
  END LOOP;

  -- Calculate average interval
  IF array_length(v_intervals, 1) > 0 THEN
    v_avg_interval := (SELECT AVG(val) FROM unnest(v_intervals) AS val);
  END IF;

  -- Calculate variance
  IF array_length(v_intervals, 1) > 0 THEN
    v_variance := (SELECT SQRT(AVG(POWER(val - v_avg_interval, 2))) FROM unnest(v_intervals) AS val);
    v_variance_minutes := ROUND(v_variance * 60)::INTEGER;
  END IF;

  -- Base confidence on occurrences
  v_base_confidence := LEAST(v_event_count * 15, 60);

  -- Check for fixed-interval pattern (variance < 2 hours)
  IF v_variance_minutes < 120 THEN
    pattern_type := 'fixed-interval';
    pattern_interval := ROUND(v_avg_interval * 10) / 10;
    pattern_time_of_day := NULL;
    
    -- Adjust confidence based on variance
    IF v_variance_minutes < 15 THEN
      confidence := v_base_confidence + 35;
    ELSIF v_variance_minutes < 60 THEN
      confidence := v_base_confidence + 20;
    ELSE
      confidence := v_base_confidence + 10;
    END IF;
  ELSE
    -- Check for fixed-time pattern (same time of day)
    FOR v_events IN
      SELECT 
        TO_CHAR(event_timestamp AT TIME ZONE 'UTC', 'HH24:MI') as time_key,
        COUNT(*) as count
      FROM detect_restart_events(p_server_id, p_days_back)
      GROUP BY TO_CHAR(event_timestamp AT TIME ZONE 'UTC', 'HH24:MI')
      ORDER BY COUNT(*) DESC
    LOOP
      IF v_events.count > v_max_occurrences THEN
        v_max_occurrences := v_events.count;
        v_most_common_time := v_events.time_key;
      END IF;
    END LOOP;

    -- If at least 50% of restarts happen at the same time
    IF v_max_occurrences >= v_event_count * 0.5 THEN
      pattern_type := 'fixed-time';
      pattern_interval := NULL;
      pattern_time_of_day := v_most_common_time;
      
      -- Adjust confidence based on variance
      IF v_variance_minutes < 30 THEN
        confidence := v_base_confidence + 30;
      ELSIF v_variance_minutes < 120 THEN
        confidence := v_base_confidence + 15;
      ELSE
        confidence := v_base_confidence + 5;
      END IF;
    ELSE
      -- Irregular pattern
      pattern_type := 'irregular';
      pattern_interval := NULL;
      pattern_time_of_day := NULL;
      confidence := v_base_confidence + 5;
    END IF;
  END IF;

  -- Cap confidence at 100
  confidence := LEAST(confidence, 100);
  pattern_occurrences := v_event_count;

  RETURN NEXT;
END;
$$ LANGUAGE plpgsql STABLE;

-- ============================================================================
-- 5. MAIN FUNCTION: Calculate Restart Predictions
-- ============================================================================

CREATE OR REPLACE FUNCTION calculate_server_restart_predictions(
  p_server_id TEXT DEFAULT NULL,
  p_days_back INTEGER DEFAULT 14
)
RETURNS TABLE (
  server_id TEXT,
  next_restart_time TIMESTAMP WITH TIME ZONE,
  confidence INTEGER,
  detected_pattern TEXT,
  last_restart_time TIMESTAMP WITH TIME ZONE,
  average_downtime INTEGER,
  pattern_type TEXT,
  pattern_occurrences INTEGER
) AS $$
DECLARE
  v_server_id TEXT;
  v_events RECORD;
  v_pattern RECORD;
  v_event_count INTEGER := 0;
  v_last_restart TIMESTAMP WITH TIME ZONE;
  v_avg_downtime INTEGER := 0;
  v_total_downtime INTEGER := 0;
  v_pattern_type TEXT;
  v_confidence INTEGER;
  v_next_restart TIMESTAMP WITH TIME ZONE;
  v_detected_pattern TEXT;
  v_pattern_interval NUMERIC;
  v_pattern_time_of_day TEXT;
  v_hours INTEGER;
  v_minutes INTEGER;
BEGIN
  -- If no specific server, process all servers
  IF p_server_id IS NULL THEN
    FOR v_server_id IN
      SELECT DISTINCT server_id FROM player_counts
      WHERE timestamp >= NOW() - (p_days_back || ' days')::INTERVAL
    LOOP
      -- Recursively call for each server
      FOR v_events IN
        SELECT * FROM calculate_server_restart_predictions(v_server_id, p_days_back)
      LOOP
        server_id := v_events.server_id;
        next_restart_time := v_events.next_restart_time;
        confidence := v_events.confidence;
        detected_pattern := v_events.detected_pattern;
        last_restart_time := v_events.last_restart_time;
        average_downtime := v_events.average_downtime;
        pattern_type := v_events.pattern_type;
        pattern_occurrences := v_events.pattern_occurrences;
        RETURN NEXT;
      END LOOP;
    END LOOP;
    RETURN;
  END IF;

  -- Get restart events for this server
  FOR v_events IN
    SELECT event_timestamp, downtime_minutes FROM detect_restart_events(p_server_id, p_days_back)
    ORDER BY event_timestamp DESC
  LOOP
    v_event_count := v_event_count + 1;
    IF v_event_count = 1 THEN
      v_last_restart := v_events.event_timestamp;
    END IF;
    v_total_downtime := v_total_downtime + v_events.downtime_minutes;
  END LOOP;

  -- Calculate average downtime
  IF v_event_count > 0 THEN
    v_avg_downtime := v_total_downtime / v_event_count;
  END IF;

  -- Get pattern analysis
  FOR v_pattern IN
    SELECT * FROM analyze_restart_pattern(p_server_id, p_days_back)
  LOOP
    v_pattern_type := v_pattern.pattern_type;
    v_confidence := v_pattern.confidence;
    v_pattern_interval := v_pattern.pattern_interval;
    v_pattern_time_of_day := v_pattern.pattern_time_of_day;
  END LOOP;

  -- Determine detected pattern description
  IF v_pattern_type = 'insufficient-data' THEN
    v_detected_pattern := NULL;
    v_next_restart := NULL;
  ELSIF v_pattern_type = 'fixed-interval' AND v_pattern_interval IS NOT NULL THEN
    v_hours := FLOOR(v_pattern_interval)::INTEGER;
    v_minutes := ROUND((v_pattern_interval - FLOOR(v_pattern_interval)) * 60)::INTEGER;
    
    IF v_hours = 1 THEN
      v_detected_pattern := 'Every hour';
    ELSIF v_hours = 24 THEN
      v_detected_pattern := 'Daily';
    ELSE
      v_detected_pattern := 'Every ' || v_hours || ' hours';
    END IF;
    
    -- Predict next restart
    IF v_last_restart IS NOT NULL THEN
      v_next_restart := v_last_restart + (v_pattern_interval || ' hours')::INTERVAL;
    END IF;
  ELSIF v_pattern_type = 'fixed-time' AND v_pattern_time_of_day IS NOT NULL THEN
    v_detected_pattern := 'Daily at ' || v_pattern_time_of_day || ' UTC';
    
    -- Predict next restart at that time
    -- Extract hours and minutes from the time string
    v_next_restart := DATE_TRUNC('day', NOW() AT TIME ZONE 'UTC')::TIMESTAMP WITH TIME ZONE 
                      + (v_pattern_time_of_day || ':00')::TIME;
    
    -- If that time has passed, use tomorrow
    IF v_next_restart <= NOW() THEN
      v_next_restart := DATE_TRUNC('day', NOW() AT TIME ZONE 'UTC')::TIMESTAMP WITH TIME ZONE 
                        + INTERVAL '1 day'
                        + (v_pattern_time_of_day || ':00')::TIME;
    END IF;
  ELSE
    v_detected_pattern := 'Irregular restarts';
    v_next_restart := NULL;
  END IF;

  -- Return results
  server_id := p_server_id;
  next_restart_time := v_next_restart;
  confidence := v_confidence;
  detected_pattern := v_detected_pattern;
  last_restart_time := v_last_restart;
  average_downtime := v_avg_downtime;
  pattern_type := v_pattern_type;
  pattern_occurrences := v_event_count;

  RETURN NEXT;
END;
$$ LANGUAGE plpgsql STABLE;

-- ============================================================================
-- 6. FUNCTION: Refresh All Predictions
-- ============================================================================

CREATE OR REPLACE FUNCTION refresh_all_restart_predictions()
RETURNS TABLE (
  servers_processed INTEGER,
  predictions_updated INTEGER,
  last_run TIMESTAMP WITH TIME ZONE
) AS $$
DECLARE
  v_server_id TEXT;
  v_prediction RECORD;
  v_servers_processed INTEGER := 0;
  v_predictions_updated INTEGER := 0;
BEGIN
  -- Get all unique servers
  FOR v_server_id IN
    SELECT DISTINCT server_id FROM player_counts
    WHERE timestamp >= NOW() - INTERVAL '30 days'
  LOOP
    v_servers_processed := v_servers_processed + 1;

    -- Calculate predictions for this server
    FOR v_prediction IN
      SELECT * FROM calculate_server_restart_predictions(v_server_id, 14)
    LOOP
      -- Upsert into predictions table
      INSERT INTO server_restart_predictions (
        server_id,
        next_restart_time,
        confidence,
        detected_pattern,
        last_restart_time,
        average_downtime,
        pattern_type,
        pattern_interval,
        pattern_time_of_day,
        pattern_variance,
        pattern_occurrences,
        detected_events_count,
        updated_at
      ) VALUES (
        v_prediction.server_id,
        v_prediction.next_restart_time,
        v_prediction.confidence,
        v_prediction.detected_pattern,
        v_prediction.last_restart_time,
        v_prediction.average_downtime,
        v_prediction.pattern_type,
        NULL,
        NULL,
        0,
        v_prediction.pattern_occurrences,
        v_prediction.pattern_occurrences,
        NOW()
      )
      ON CONFLICT (server_id) DO UPDATE SET
        next_restart_time = EXCLUDED.next_restart_time,
        confidence = EXCLUDED.confidence,
        detected_pattern = EXCLUDED.detected_pattern,
        last_restart_time = EXCLUDED.last_restart_time,
        average_downtime = EXCLUDED.average_downtime,
        pattern_type = EXCLUDED.pattern_type,
        pattern_occurrences = EXCLUDED.pattern_occurrences,
        detected_events_count = EXCLUDED.detected_events_count,
        updated_at = NOW();

      v_predictions_updated := v_predictions_updated + 1;
    END LOOP;
  END LOOP;

  servers_processed := v_servers_processed;
  predictions_updated := v_predictions_updated;
  last_run := NOW();

  RETURN NEXT;
END;
$$ LANGUAGE plpgsql;

