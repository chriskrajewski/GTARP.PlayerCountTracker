-- =====================================================
-- Recorded Restart Predictions Schema
-- =====================================================
-- Purpose: Snapshot Restart_Predictor output and match it against observed
--          restarts so the Prediction_Accuracy_Tracker can compute accuracy
--          metrics over a rolling window.
--          - R6.1: record each prediction's predicted restart time, confidence,
--                  and the time the prediction was made.
--          - R6.2: when a restart is detected, fill in the observed restart
--                  time and the signed difference (in minutes) against the
--                  most recent applicable recorded prediction.
--          `lib/restart-prediction.ts` does not persist its output, so this
--          table is the new data dependency for accuracy tracking.
--
-- Access:  Writes come from the server-side prediction-recording cron (via the
--          service-role client); the predictions tab reads the rolling accuracy.
--
-- Migration: Defined in client-agnostic terms (explicit columns, types, and
--          indexes) so it stays expressible in both the current schema and a
--          Prisma schema during the in-flight RDS migration (R9.2).
-- =====================================================

-- Create the recorded_restart_predictions table
create table if not exists public.recorded_restart_predictions (
  id bigint generated by default as identity not null,
  server_id text not null,
  predicted_restart_time timestamp with time zone not null,
  confidence integer not null,
  prediction_made_at timestamp with time zone not null default now(),
  observed_restart_time timestamp with time zone null,
  difference_minutes integer null,
  matched_at timestamp with time zone null,
  constraint recorded_restart_predictions_pkey primary key (id)
);

-- Composite index for fetching a server's recent predictions (R6.1 reads)
create index if not exists idx_recorded_predictions_server_made
  on public.recorded_restart_predictions using btree (server_id, prediction_made_at desc);

-- Index for rolling-window scans across all servers (R6.3 accuracy window)
create index if not exists idx_recorded_predictions_made
  on public.recorded_restart_predictions using btree (prediction_made_at desc);

-- Composite index for matching detected restarts to unmatched predictions (R6.2)
create index if not exists idx_recorded_predictions_server_observed
  on public.recorded_restart_predictions using btree (server_id, observed_restart_time);

