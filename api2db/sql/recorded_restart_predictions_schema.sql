comment on table public.recorded_restart_predictions is 'Snapshots of restart predictions matched against observed restarts for accuracy tracking (R6.1/R6.2).';
comment on column public.recorded_restart_predictions.id is 'Primary key, auto-incrementing';
comment on column public.recorded_restart_predictions.server_id is 'FiveM server identifier the prediction applies to';
comment on column public.recorded_restart_predictions.predicted_restart_time is 'Predicted next restart time from the Restart_Predictor (R6.1)';
comment on column public.recorded_restart_predictions.confidence is 'Confidence value of the prediction at the time it was made (R6.1)';
comment on column public.recorded_restart_predictions.prediction_made_at is 'Time the prediction was recorded (R6.1)';
comment on column public.recorded_restart_predictions.observed_restart_time is 'Actual observed restart time, filled in when a restart is matched (R6.2)';
comment on column public.recorded_restart_predictions.difference_minutes is 'Signed difference in minutes between predicted and observed restart times (R6.2)';
comment on column public.recorded_restart_predictions.matched_at is 'Time the prediction was matched to an observed restart';
